// Package iframe provides the iframe element.
//
// The [Iframe] element embeds another HTML document.
//
// Attributes:
//   - [Src]: URL of the embedded document
//   - [Srcdoc]: Inline HTML content
//   - [Name]: Browsing context name
//   - [Width], [Height]: Frame dimensions
//   - [Sandbox]: Security restrictions
//   - [Allow]: Feature policy
//   - [Loading]: Lazy loading (lazy, eager)
//   - [Referrerpolicy]: Referrer policy
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/iframe
