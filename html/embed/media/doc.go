//   - [Video]: Video player
//   - [Audio]: Audio player
//   - [Source]: Media source
//   - [Track]: Text tracks (subtitles, captions)
//
// Common media attributes:
//   - [Src]: Media URL
//   - [Controls]: Show playback controls
//   - [Autoplay]: Start playing automatically
//   - [Loop]: Loop playback
//   - [Muted]: Start muted
//   - [Preload]: Preloading behavior (none, metadata, auto)
//
// Video-specific:
//   - [Poster]: Poster image URL
//   - [Width], [Height]: Player dimensions
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/video
