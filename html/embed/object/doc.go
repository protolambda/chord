// Package object provides object, embed, and param elements.
//
// Elements:
//   - [Object]: External resource (legacy)
//   - [Embed]: External content plugin (legacy)
//   - [Param]: Parameters for object
//
// Object attributes:
//   - [Data]: Resource URL
//   - [Type]: MIME type
//   - [Name]: Name for form submission
//   - [Width], [Height]: Dimensions
//
// Embed attributes:
//   - [Src]: Resource URL
//   - [Type]: MIME type
//   - [Width], [Height]: Dimensions
//
// Note: Object and embed are legacy elements. Prefer iframe, video, audio, or img.
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/object
package object
