// Package aria provides ARIA (Accessible Rich Internet Applications) attributes.
//
// ARIA attributes improve accessibility for users of assistive technologies.
//
// Common attributes:
//   - [Role]: Define the element's role
//   - [Label]: Accessible name for the element
//   - [Labelledby]: Reference to labeling element
//   - [Describedby]: Reference to describing element
//   - [Hidden]: Hide from accessibility tree
//   - [Expanded]: Expandable element state
//   - [Selected]: Selection state
//   - [Checked]: Checkbox/radio state
//   - [Disabled]: Disabled state
//   - [Live]: Live region announcements
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/Accessibility/ARIA/Attributes
