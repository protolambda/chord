// Package textarea provides the textarea element and its attributes.
//
// The [Textarea] element creates multi-line text input.
//
// Common attributes:
//   - [Name]: Form submission name
//   - [Rows], [Cols]: Visible dimensions
//   - [Placeholder]: Hint text
//   - [Required], [Disabled], [Readonly]: States
//   - [Minlength], [Maxlength]: Text length constraints
//   - [Wrap]: Text wrapping behavior (soft, hard)
//   - [Autocomplete]: Browser autofill hints
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/textarea
