// Package button provides the button element and its attributes.
//
// The [Button] element creates clickable buttons.
//
// Type attribute values:
//   - submit: Submits the form (default)
//   - reset: Resets the form
//   - button: No default behavior
//
// Common attributes:
//   - [Type]: Button type
//   - [Name], [Value]: Form submission
//   - [Disabled]: Disabled state
//   - [Formaction], [Formmethod]: Override form attributes
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/button
package button
