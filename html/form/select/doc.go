// Package select provides select, option, and optgroup elements.
//
// Elements:
//   - [Select]: Dropdown selection control
//   - [Option]: Selection option
//   - [Optgroup]: Group of options
//
// Select attributes:
//   - [Name]: Form submission name
//   - [Multiple]: Allow multiple selections
//   - [Size]: Visible options count
//   - [Required], [Disabled]: States
//
// Option attributes:
//   - [Value]: Submission value
//   - [Selected]: Initially selected
//   - [Disabled]: Disabled option
//
// Note: This package is imported as "selectel" due to Go's reserved keyword.
//
// Reference: https://developer.mozilla.org/en-US/docs/Web/HTML/Element/select
package selectel
